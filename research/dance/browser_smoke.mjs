import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base = process.env.PIPELINE_URL || 'http://localhost:3001';
const browser = await chromium.launch({ headless: true,
  executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args: ['--mute-audio'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${base}/pipeline`);
  await page.getByRole('heading', { name: 'Inside the pipeline.' }).waitFor();
  await page.waitForFunction(() => document.querySelector('.pl-state')?.textContent?.includes('Ready for review'), null, { timeout: 180000 });
  await page.waitForFunction(() => document.querySelector('video')?.readyState >= 2);
  const selectedRun = await page.getByLabel('Run history').inputValue();
  const source = await page.request.get(`${base}/api/pipeline?run=${selectedRun}`);
  const snapshot = await source.json();
  assert.equal(snapshot.state, 'complete');
  assert.ok(snapshot.result.frames > 0);
  const poseResponse = await page.request.get(`${base}/api/pipeline?run=${selectedRun}&view=frames`);
  const frames = await poseResponse.json();
  const trackedFrame = frames.find(f => f.primary !== null && f.t > 2);
  assert.ok(trackedFrame, 'At least one real primary pose must exist');
  const scrubber = page.getByRole('slider', { name: 'Scrub video and audio' });
  await scrubber.fill((trackedFrame.t + 0.001).toFixed(3));
  await page.waitForFunction(() => document.querySelector('.pl-primary-label'));
  assert.ok(await page.locator('.pl-skeleton line').count() > 0);
  const before = await page.locator('video').evaluate(v => v.currentTime);
  await page.getByRole('button', { name: 'Next frame', exact: true }).click();
  await page.waitForFunction(t => document.querySelector('video').currentTime > t, before);
  const after = await page.locator('video').evaluate(v => v.currentTime);
  assert.ok(after - before < .06, 'Frame stepping should advance one decoded frame');
  await page.getByLabel('Playback speed').selectOption('0.5');
  assert.equal(await page.locator('video').evaluate(v => v.playbackRate), .5);
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.waitForFunction(t => document.querySelector('video').currentTime > t + .2, after);
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.getByLabel('Skeleton only', { exact: true }).check();
  assert.equal(await page.locator('video').evaluate(v => getComputedStyle(v).opacity), '0');
  await page.getByLabel('Skeleton only', { exact: true }).uncheck();
  await page.getByLabel('Skeleton overlay', { exact: true }).uncheck();
  assert.equal(await page.locator('.pl-skeleton').count(), 0);
  await page.getByLabel('Skeleton overlay', { exact: true }).check();
  const note = 'Automated QA: verified synchronized seeking, frame stepping, playback speed, skeleton toggles, and persistent timestamped notes. This is not a choreography judgment.';
  await page.locator('#pipeline-note').fill(note);
  await page.getByRole('button', { name: 'Save timestamped note', exact: true }).click();
  await page.getByText(note, { exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: /Review notes/ }).click();
  await page.getByText(note, { exact: true }).waitFor();
  await page.getByRole('button', { name: /Processing log/ }).click();
  await scrubber.fill((trackedFrame.t + .001).toFixed(3));
  await page.waitForFunction(() => document.querySelector('.pl-primary-label'));
  await page.screenshot({ path: '/private/tmp/lightflow-pipeline-verified-desktop.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/private/tmp/lightflow-pipeline-verified-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const media = `${base}/api/pipeline/asset?run=${selectedRun}&file=preview.mp4`;
  const range = await page.request.get(media, { headers: { Range: 'bytes=0-99' } });
  assert.equal(range.status(), 206); assert.equal((await range.body()).length, 100);
  assert.equal((await page.request.get(media, { headers: { Range: 'bytes=-0' } })).status(), 416);
  const rejected = await page.request.post(`${base}/api/pipeline`, { headers: { Origin: 'https://example.com' }, data: { action: 'start' } });
  assert.equal(rejected.status(), 400);
  const invalid = await page.request.post(`${base}/api/pipeline`, { headers: { Origin: base }, data: { action: 'start', sourceId: snapshot.job.sourceId, start: -1, duration: 20 } });
  assert.equal(invalid.status(), 400);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, run: selectedRun, frames: snapshot.result.frames, coverage: snapshot.result.coverage, checks: ['real poses', 'scrubbing', 'frame stepping', 'audio/video playback', 'speed', 'overlays', 'note persistence', 'desktop/mobile overflow', 'media ranges', 'invalid requests'], errors }, null, 2));
} finally { await browser.close(); }
