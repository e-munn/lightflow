"""Dataset for loading audio + stem energy label pairs.

Training data consists of audio files paired with 6-channel stem energy envelopes
generated by demucs separation: bass, kick, snare, hats, vocals, other.

Includes:
  - LightFlowDataset: stateless window-based dataset (for CNN/LSTM)
  - LightFlowSequenceDataset: sequence dataset with cached features (for StreamingGRU)
  - SilenceNoiseDataset: synthetic silence/noise for gate head training
"""

import json
from pathlib import Path

import librosa
import numpy as np
import torch
from torch.utils.data import Dataset

from .features import AudioFeatureExtractor


STEM_CHANNELS = [
    "bass_energy",
    "kick_energy",
    "snare_energy",
    "hat_energy",
    "vocals_energy",
    "other_energy",
]


class LightFlowDataset(Dataset):
    """Loads (audio_window, stem_energy) pairs for training.

    Expected data directory structure:
        data/
            track_001/
                audio.wav
                labels.json
            track_002/
                ...

    labels.json format:
        {
            "fps": 20,
            "channels": ["bass_energy", "kick_energy", ...],
            "states": [
                {"time": 0.0, "channels": {"bass_energy": 0.8, "kick_energy": 0.3, ...}},
                ...
            ]
        }
    """

    def __init__(self, data_dir: str, config: dict, split: str = "train"):
        self.data_dir = Path(data_dir)
        self.config = config
        self.split = split
        self.feature_extractor = AudioFeatureExtractor(config)

        audio_cfg = config["audio"]
        self.sample_rate = audio_cfg["sample_rate"]
        self.window_seconds = audio_cfg["window_seconds"]
        self.hop_seconds = audio_cfg["hop_seconds"]
        self.window_samples = int(self.window_seconds * self.sample_rate)
        self.hop_samples = int(self.hop_seconds * self.sample_rate)

        self.output_dim = config["model"]["output_dim"]
        self.augment_cfg = config["data"].get("augment", {})
        self.do_augment = split == "train" and bool(self.augment_cfg)

        # Discover songs, split, cache labels
        self.songs = self._discover_songs()
        self._cache_labels()
        self.windows = self._build_window_index()

    def _discover_songs(self) -> list[dict]:
        """Find all song directories with audio + labels."""
        songs = []
        if not self.data_dir.exists():
            return songs

        for song_dir in sorted(self.data_dir.iterdir()):
            if not song_dir.is_dir():
                continue

            audio_file = None
            for ext in [".wav", ".mp3", ".flac", ".ogg"]:
                candidate = song_dir / f"audio{ext}"
                if candidate.exists():
                    audio_file = candidate
                    break

            labels_file = song_dir / "labels.json"
            if audio_file and labels_file.exists():
                songs.append({
                    "audio": audio_file,
                    "labels": labels_file,
                    "name": song_dir.name,
                })

        # Track-level split (75/12.5/12.5)
        n = len(songs)
        train_end = int(n * self.config["data"]["train_split"])
        val_end = train_end + int(n * self.config["data"]["val_split"])

        if self.split == "train":
            return songs[:train_end]
        elif self.split == "val":
            return songs[train_end:val_end]
        else:
            return songs[val_end:]

    def _cache_labels(self):
        """Load all labels into memory to avoid re-parsing JSON per __getitem__."""
        self._labels_cache = {}
        for song_idx, song in enumerate(self.songs):
            with open(song["labels"]) as f:
                data = json.load(f)
            # Pre-convert states to numpy array: (n_states, 6)
            states = data["states"]
            n_states = len(states)
            label_array = np.zeros((n_states, self.output_dim), dtype=np.float32)
            for i, state in enumerate(states):
                channels = state["channels"]
                for j, ch_name in enumerate(STEM_CHANNELS[:self.output_dim]):
                    label_array[i, j] = channels.get(ch_name, 0.0)
            self._labels_cache[song_idx] = {
                "fps": data["fps"],
                "labels": label_array,
            }

    def _build_window_index(self) -> list[tuple[int, int]]:
        """Build list of (song_idx, start_sample) for all windows."""
        windows = []
        for song_idx, song in enumerate(self.songs):
            duration = librosa.get_duration(path=song["audio"])
            total_samples = int(duration * self.sample_rate)
            start = 0
            while start + self.window_samples <= total_samples:
                windows.append((song_idx, start))
                start += self.hop_samples
        return windows

    def _augment(self, y: np.ndarray) -> np.ndarray:
        """Apply data augmentation to audio window."""
        # Gain jitter
        gain_range = self.augment_cfg.get("gain_jitter")
        if gain_range:
            gain = np.random.uniform(gain_range[0], gain_range[1])
            y = y * gain

        # Additive noise
        noise_level = self.augment_cfg.get("noise_level", 0.0)
        if noise_level > 0:
            noise = np.random.randn(len(y)).astype(np.float32) * noise_level
            y = y + noise

        return y

    def __len__(self) -> int:
        return len(self.windows)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, torch.Tensor]:
        song_idx, start_sample = self.windows[idx]
        song = self.songs[song_idx]

        # Load audio window
        start_sec = start_sample / self.sample_rate
        y, _ = librosa.load(
            song["audio"],
            sr=self.sample_rate,
            offset=start_sec,
            duration=self.window_seconds,
            mono=True,
        )

        # Pad if needed
        if len(y) < self.window_samples:
            y = np.pad(y, (0, self.window_samples - len(y)))

        # Augment
        if self.do_augment:
            y = self._augment(y)

        # Extract features
        features = self.feature_extractor.extract(y)
        feature_array = self.feature_extractor.concat_features(features)

        # Look up cached label
        cached = self._labels_cache[song_idx]
        label_fps = cached["fps"]
        labels = cached["labels"]

        # Find the label closest to the center of this window
        center_time = start_sec + self.window_seconds / 2
        label_idx = min(int(center_time * label_fps), len(labels) - 1)
        label_vector = labels[label_idx]

        return (
            torch.from_numpy(feature_array).float(),
            torch.from_numpy(label_vector).float(),
        )


class LightFlowSequenceDataset(Dataset):
    """Sequence dataset for StreamingGRU training.

    Returns sequences of (features, labels, future_labels, gate_labels) where
    features are pre-extracted and cached as .npy files per track for speed.

    Each sample is a contiguous sequence of `seq_len` windows from a single track.
    """

    def __init__(self, data_dir: str, config: dict, split: str = "train"):
        self.data_dir = Path(data_dir)
        self.config = config
        self.split = split
        self.feature_extractor = AudioFeatureExtractor(config)

        audio_cfg = config["audio"]
        self.sample_rate = audio_cfg["sample_rate"]
        self.window_seconds = audio_cfg["window_seconds"]
        self.hop_seconds = audio_cfg["hop_seconds"]
        self.window_samples = int(self.window_seconds * self.sample_rate)
        self.hop_samples = int(self.hop_seconds * self.sample_rate)

        model_cfg = config["model"]
        self.output_dim = model_cfg["output_dim"]
        self.seq_len = model_cfg.get("seq_len", 64)
        self.n_future = model_cfg.get("n_future", 4)

        self.overlap = config["data"].get("seq_overlap", 0.5)
        self.augment_cfg = config["data"].get("augment", {})
        self.do_augment = split == "train" and bool(self.augment_cfg)

        # Discover and split songs
        self.songs = self._discover_songs()
        self._cache_labels()

        # Extract/load cached features
        self._feature_cache = {}
        self._cache_features()

        # Build sequence index
        self.sequences = self._build_sequence_index()

    def _discover_songs(self) -> list[dict]:
        """Find all song directories with audio + labels."""
        songs = []
        if not self.data_dir.exists():
            return songs

        for song_dir in sorted(self.data_dir.iterdir()):
            if not song_dir.is_dir():
                continue
            audio_file = None
            for ext in [".wav", ".mp3", ".flac", ".ogg"]:
                candidate = song_dir / f"audio{ext}"
                if candidate.exists():
                    audio_file = candidate
                    break
            labels_file = song_dir / "labels.json"
            if audio_file and labels_file.exists():
                songs.append({
                    "audio": audio_file,
                    "labels": labels_file,
                    "name": song_dir.name,
                    "dir": song_dir,
                })

        n = len(songs)
        train_end = int(n * self.config["data"]["train_split"])
        val_end = train_end + int(n * self.config["data"]["val_split"])

        if self.split == "train":
            return songs[:train_end]
        elif self.split == "val":
            return songs[train_end:val_end]
        else:
            return songs[val_end:]

    def _cache_labels(self):
        """Load all labels into memory."""
        self._labels_cache = {}
        for song_idx, song in enumerate(self.songs):
            with open(song["labels"]) as f:
                data = json.load(f)
            states = data["states"]
            n_states = len(states)
            label_array = np.zeros((n_states, self.output_dim), dtype=np.float32)
            for i, state in enumerate(states):
                channels = state["channels"]
                for j, ch_name in enumerate(STEM_CHANNELS[:self.output_dim]):
                    label_array[i, j] = channels.get(ch_name, 0.0)
            self._labels_cache[song_idx] = {
                "fps": data["fps"],
                "labels": label_array,
            }

    def _cache_features(self):
        """Extract features per track and cache as .npy files.

        First run is slow (~minutes per track with librosa), subsequent runs
        load instantly from cache.
        """
        for song_idx, song in enumerate(self.songs):
            cache_file = song["dir"] / "features.npy"

            if cache_file.exists():
                self._feature_cache[song_idx] = np.load(cache_file)
                continue

            print(f"  Extracting features for {song['name']}...")
            y, _ = librosa.load(song["audio"], sr=self.sample_rate, mono=True)

            # Extract features for every hop window across the full track
            all_features = []
            pos = 0
            while pos + self.window_samples <= len(y):
                window = y[pos:pos + self.window_samples]
                features = self.feature_extractor.extract(window)
                feature_array = self.feature_extractor.concat_features(features)
                # Global pool each window to a single feature vector
                feature_vec = feature_array.mean(axis=0)  # (143,)
                all_features.append(feature_vec)
                pos += self.hop_samples

            features_np = np.stack(all_features).astype(np.float32)  # (n_windows, 143)
            np.save(cache_file, features_np)
            self._feature_cache[song_idx] = features_np

    def _build_sequence_index(self) -> list[tuple[int, int]]:
        """Build list of (song_idx, start_window) for all sequences."""
        sequences = []
        step = max(1, int(self.seq_len * (1 - self.overlap)))

        for song_idx in range(len(self.songs)):
            n_windows = len(self._feature_cache[song_idx])
            # Need seq_len + n_future windows to get future labels for last step
            max_start = n_windows - self.seq_len - self.n_future
            start = 0
            while start <= max_start:
                sequences.append((song_idx, start))
                start += step

        return sequences

    def __len__(self) -> int:
        return len(self.sequences)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, torch.Tensor,
                                              torch.Tensor, torch.Tensor]:
        song_idx, start_win = self.sequences[idx]
        features_all = self._feature_cache[song_idx]
        cached = self._labels_cache[song_idx]
        label_fps = cached["fps"]
        labels_all = cached["labels"]

        # Feature sequence: (seq_len, 143) — pre-pooled feature vectors
        feat_seq = features_all[start_win:start_win + self.seq_len].copy()

        if self.do_augment:
            gain_range = self.augment_cfg.get("gain_jitter")
            if gain_range:
                gain = np.random.uniform(gain_range[0], gain_range[1])
                feat_seq = feat_seq * gain
            noise_level = self.augment_cfg.get("noise_level", 0.0)
            if noise_level > 0:
                feat_seq = feat_seq + np.random.randn(*feat_seq.shape).astype(np.float32) * noise_level

        # Labels: map window indices to label indices
        energy_labels = np.zeros((self.seq_len, self.output_dim), dtype=np.float32)
        future_labels = np.zeros((self.seq_len, self.n_future, self.output_dim), dtype=np.float32)
        gate_labels = np.ones((self.seq_len, 1), dtype=np.float32)  # 1 = music

        for s in range(self.seq_len):
            win_idx = start_win + s
            center_time = (win_idx * self.hop_samples + self.window_samples / 2) / self.sample_rate
            label_idx = min(int(center_time * label_fps), len(labels_all) - 1)
            energy_labels[s] = labels_all[label_idx]

            # Future labels at each horizon
            for f in range(self.n_future):
                future_win = win_idx + f + 1
                future_time = (future_win * self.hop_samples + self.window_samples / 2) / self.sample_rate
                future_label_idx = min(int(future_time * label_fps), len(labels_all) - 1)
                future_labels[s, f] = labels_all[future_label_idx]

            # Gate: 1 if RMS of label vector > threshold, else 0
            if np.max(energy_labels[s]) < 0.02:
                gate_labels[s] = 0.0

        return (
            torch.from_numpy(feat_seq).float(),           # (seq_len, 143)
            torch.from_numpy(energy_labels).float(),       # (seq_len, output_dim)
            torch.from_numpy(future_labels).float(),       # (seq_len, n_future, output_dim)
            torch.from_numpy(gate_labels).float(),         # (seq_len, 1)
        )


class SilenceNoiseDataset(Dataset):
    """Synthetic silence/noise dataset for gate head training.

    Generates random silence and noise windows with gate_label=0
    to teach the gate head to detect non-music audio.
    """

    def __init__(self, n_samples: int, config: dict):
        self.n_samples = n_samples
        self.output_dim = config["model"]["output_dim"]
        self.seq_len = config["model"].get("seq_len", 64)
        self.n_future = config["model"].get("n_future", 4)
        self.feature_dim = config["model"]["input_channels"]

    def __len__(self) -> int:
        return self.n_samples

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, torch.Tensor,
                                              torch.Tensor, torch.Tensor]:
        # Random low-energy features (simulating silence/noise)
        noise_level = np.random.uniform(0.0, 0.05)
        feat_seq = np.random.randn(self.seq_len, self.feature_dim).astype(np.float32) * noise_level

        # All-zero labels (silence has no stem energy)
        energy_labels = np.zeros((self.seq_len, self.output_dim), dtype=np.float32)
        future_labels = np.zeros((self.seq_len, self.n_future, self.output_dim), dtype=np.float32)
        gate_labels = np.zeros((self.seq_len, 1), dtype=np.float32)  # 0 = silence

        return (
            torch.from_numpy(feat_seq).float(),
            torch.from_numpy(energy_labels).float(),
            torch.from_numpy(future_labels).float(),
            torch.from_numpy(gate_labels).float(),
        )
