import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
const base='http://localhost:3001';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--mute-audio','--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{
  const original=navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices);
  navigator.mediaDevices.getUserMedia=async constraints=>{const stream=await original(constraints);window.__qaStream=stream;return stream;};
 });
 await page.goto(base+'/pipeline/model');
 await page.waitForFunction(()=>!!document.querySelector('audio')?.getAttribute('src'),{},{timeout:60000});
 const selected=await page.getByLabel('Model study music').inputValue();assert.ok(selected);
 await page.getByLabel('Seek model comparison').fill('3');
 await page.waitForFunction(()=>[...document.querySelectorAll('.dm-field')].every(x=>x.dataset.value!=='missing'));
 const levels=await page.locator('.dm-field').evaluateAll(els=>els.map(e=>Number(e.dataset.value)));
 assert.ok(levels.every(x=>Number.isFinite(x)&&x>=0&&x<=1));
 const config=JSON.parse(fs.readFileSync('research/dance/training.local.json','utf8'));
 const predictions=JSON.parse(fs.readFileSync(path.join(config.directory,selected+'.json'),'utf8')).frames;
 const expected=predictions.find(f=>Math.abs(f.t-3)<.001);
 assert.ok(Math.abs(expected.movement-levels[0])<.03,'Browser decoding/inference should match offline training pipeline within resampling tolerance');
 assert.ok(Math.abs(expected.direct-levels[1])<.03);
 await page.locator('audio').evaluate(a=>a.play());
 await page.waitForFunction(()=>document.querySelector('audio').currentTime>3.5);
 await page.locator('audio').evaluate(a=>a.pause());
 await page.getByRole('button',{name:'Expand Audio → movement → light',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.dm-full').classList.contains('active'));
 const full=await page.locator('.dm-full').boundingBox();
 assert.ok(full.width>=1439&&full.height>=1049,'Fullscreen must fill viewport, not a square');
 await page.getByRole('button',{name:'Close · Audio → movement → light',exact:true}).click();
 await page.getByRole('button',{name:'Use microphone',exact:true}).click();
 await page.getByRole('button',{name:'Stop microphone',exact:true}).waitFor({timeout:20000});
 await page.waitForFunction(()=>document.querySelector('.dm-field')?.dataset.value!=='missing');
 await page.getByRole('button',{name:'Stop microphone',exact:true}).click();
 assert.equal(await page.evaluate(()=>window.__qaStream.getTracks().every(t=>t.readyState==='ended')),true);
 const uploaded='/Volumes/ExtremePro/Movies/Assets/lightflow_research/dance/runs/'+selected+'/audio.m4a';
 await page.getByLabel('Choose audio file').setInputFiles(uploaded);
 await page.waitForFunction(()=>document.querySelector('audio')?.getAttribute('src')?.startsWith('blob:'),{},{timeout:60000});
 assert.equal(await page.getByLabel('Model study music').inputValue(),'');
 await page.getByLabel('Seek model comparison').fill('4');
 await page.waitForFunction(()=>document.querySelector('.dm-field')?.dataset.value!=='missing');
 await page.screenshot({path:'/private/tmp/lightflow-dance-model-desktop.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/private/tmp/lightflow-dance-model-mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,levels,offlineAt3:expected,checks:['held-out audio default','offline/browser prediction agreement','audio playback','viewport-filling field','synthetic microphone through worklet','microphone tracks stopped','local upload','responsive desktop/mobile']}));
}finally{await browser.close();}
